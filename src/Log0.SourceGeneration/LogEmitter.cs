using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Log0.SourceGeneration;

/// <summary>Writes the source for one type's [Log] methods.</summary>
internal static class LogEmitter
{
    #region Constants

    private const string LOGGER = "global::Microsoft.Extensions.Logging.ILogger";
    private const string NULL_LOGGER = "global::Microsoft.Extensions.Logging.Abstractions.NullLogger.Instance";
    private const string METHOD = "global::Log0.Log0Method";
    private const string EXCEPTION = "global::System.Exception";
    private const string TASKS = "global::System.Threading.Tasks";
    private const string PREFIX = "__log0";

    #endregion

    #region Public Methods

    public static string Emit( TypeModel type, IReadOnlyList< MethodModel > methods )
    {
        var writer = new Writer();
        writer.Line( "// <auto-generated/>" );
        writer.Line( "#nullable enable" );
        writer.Line( "#pragma warning disable CS0612, CS0618, CS1591" );
        writer.Line();

        if ( type.Namespace is not null )
            writer.Open( $"namespace {type.Namespace}" );

        foreach ( var container in type.Containers )
            writer.Open( container.Declaration );

        var names = new Names( Prefix( methods ) );

        if ( methods.Any( m => m.LoggerExpression is null ) )
        {
            writer.Line( GeneratedCode() );
            writer.Line( $"private static readonly global::Log0.Log0Logger {names.SharedLogger} = new( typeof( {type.TypeOfName} ) );" );
            writer.Line();
        }

        for ( var i = 0; i < methods.Count; i++ )
        {
            EmitMethod( writer, methods[ i ], names, $"{names.Prefix}_{methods[ i ].Name}_{i}" );

            if ( i < methods.Count - 1 )
                writer.Line();
        }

        foreach ( var _ in type.Containers )
            writer.Close();

        if ( type.Namespace is not null )
            writer.Close();

        return writer.ToString();
    }

    #endregion

    #region Private Methods

    /// <summary>
    /// A prefix no parameter or type parameter in the type starts with, so no generated field,
    /// local or local function can be shadowed by, or clash with, a user's name.
    /// </summary>
    private static string Prefix( IReadOnlyList< MethodModel > methods )
    {
        var reserved = methods.SelectMany( m => m.ReservedNames ).ToArray();
        var prefix = PREFIX;

        while ( reserved.Any( n => n.StartsWith( prefix, System.StringComparison.Ordinal ) ) )
            prefix += "_";

        return prefix;
    }

    private static string GeneratedCode() => "[global::System.CodeDom.Compiler.GeneratedCode( \"Log0\", \"1.0\" )]";

    private static void EmitMethod( Writer writer, MethodModel method, Names names, string field )
    {
        var parameterNames = string.Concat( method.Parameters.Select( p => $", \"{p.Name}\"" ) );
        writer.Line( GeneratedCode() );
        writer.Line( $"private static readonly {METHOD} {field} = new( \"{method.DisplayName}\", (global::Microsoft.Extensions.Logging.LogLevel){method.Level}{parameterNames} );" );
        writer.Line();

        writer.Line( GeneratedCode() );
        writer.Open( method.Signature );

        var logger = method.LoggerExpression is null
            ? $"{names.SharedLogger}.Logger"
            : $"(({LOGGER}?){method.LoggerExpression}) ?? {NULL_LOGGER}";

        writer.Line( $"{LOGGER} {names.Logger} = {logger};" );
        writer.Line( $"{METHOD} {names.Log} = {field};" );
        writer.Line();
        EmitStart( writer, method, names );
        writer.Line();

        switch ( method.Shape )
        {
            case ReturnShape.Void:
                EmitVoid( writer, method, names );
                break;
            case ReturnShape.Value:
                EmitValue( writer, method, names );
                break;
            default:
                EmitAsync( writer, method, names );
                break;
        }

        writer.Close();
    }

    private static void EmitStart( Writer writer, MethodModel method, Names n )
    {
        writer.Line( $"if ( {n.Log}.IsEnabled( {n.Logger} ) )" );

        if ( method.Parameters.Length == 0 )
        {
            writer.Line( $"    {n.Log}.Start( {n.Logger}, null );" );
            return;
        }

        var values = string.Join( ", ", method.Parameters.Select( p => p.Expression ) );
        writer.Line( $"    {n.Log}.Start( {n.Logger}, {n.Log}.IncludesParameters( {n.Logger} ) ? new object?[ ] {{ {values} }} : null );" );
    }

    /// <summary>
    /// The failure log runs as an exception filter: it sees the exception before the stack
    /// unwinds, and since it returns false the exception is never caught, so it propagates
    /// untouched. The <c>throw;</c> only satisfies definite assignment.
    /// </summary>
    private static void Catch( Writer writer, string exception, string log, string logger )
    {
        writer.Line( $"catch ( {EXCEPTION} {exception} ) when ( {log}.Failed( {logger}, {exception} ) )" );
        writer.Open();
        writer.Line( "throw;" );
        writer.Close();
    }

    private static void EmitVoid( Writer writer, MethodModel method, Names n )
    {
        writer.Open( "try" );
        writer.Line( method.CoreCall + ";" );
        writer.Close();
        Catch( writer, n.Exception, n.Log, n.Logger );
        writer.Line();
        writer.Line( $"{n.Log}.Success( {n.Logger} );" );
    }

    private static void EmitValue( Writer writer, MethodModel method, Names n )
    {
        writer.Line( $"{method.ResultType} {n.Result};" );
        writer.Line();
        writer.Open( "try" );
        writer.Line( $"{n.Result} = {method.CoreCall};" );
        writer.Close();
        Catch( writer, n.Exception, n.Log, n.Logger );
        writer.Line();
        writer.Line( $"{n.Log}.Success( {n.Logger} );" );
        writer.Line( $"return {n.Result};" );
    }

    /// <summary>
    /// The call itself runs synchronously, so an implementation that throws before returning a
    /// task still throws synchronously. A task that already succeeded is logged and returned as
    /// is; anything else is awaited in a local function, which logs when it settles.
    /// </summary>
    private static void EmitAsync( Writer writer, MethodModel method, Names n )
    {
        var (taskType, isValueTask, hasResult) = method.Shape switch
        {
            ReturnShape.Task => ($"{TASKS}.Task", false, false),
            ReturnShape.TaskOfT => ($"{TASKS}.Task<{method.ResultType}>", false, true),
            ReturnShape.ValueTask => ($"{TASKS}.ValueTask", true, false),
            _ => ($"{TASKS}.ValueTask<{method.ResultType}>", true, true)
        };

        writer.Line( $"{taskType} {n.Task};" );
        writer.Line();
        writer.Open( "try" );
        writer.Line( $"{n.Task} = {method.CoreCall};" );
        writer.Close();
        Catch( writer, n.Exception, n.Log, n.Logger );
        writer.Line();

        if ( isValueTask )
        {
            // A ValueTask may wrap a pooled source that must be read exactly once: read the
            // result here and hand back a fresh ValueTask rather than the original.
            writer.Open( $"if ( {n.Task}.IsCompletedSuccessfully )" );

            if ( hasResult )
            {
                writer.Line( $"{method.ResultType} {n.Result} = {n.Task}.Result;" );
                writer.Line( $"{n.Log}.Success( {n.Logger} );" );
                writer.Line( $"return new {taskType}( {n.Result} );" );
            }
            else
            {
                writer.Line( $"{n.Task}.GetAwaiter().GetResult();" );
                writer.Line( $"{n.Log}.Success( {n.Logger} );" );
                writer.Line( "return default;" );
            }
        }
        else
        {
            writer.Open( $"if ( {n.Task}.Status == {TASKS}.TaskStatus.RanToCompletion )" );
            writer.Line( $"{n.Log}.Success( {n.Logger} );" );
            writer.Line( $"return {n.Task};" );
        }

        writer.Close();
        writer.Line();
        writer.Line( $"return {n.Await}( {n.Task}, {n.Log}, {n.Logger} );" );
        writer.Line();

        // The local function reuses the prefixed names: its parameters shadow the outer locals,
        // which a static local function allows, and nothing can clash with the user's names.
        writer.Open( $"static async {taskType} {n.Await}( {taskType} {n.Task}, {METHOD} {n.Log}, {LOGGER} {n.Logger} )" );

        if ( hasResult )
            writer.Line( $"{method.ResultType} {n.Result};" );

        writer.Line();
        writer.Open( "try" );
        writer.Line( hasResult ? $"{n.Result} = await {n.Task}.ConfigureAwait( false );" : $"await {n.Task}.ConfigureAwait( false );" );
        writer.Close();
        Catch( writer, n.Exception, n.Log, n.Logger );
        writer.Line();
        writer.Line( $"{n.Log}.Success( {n.Logger} );" );

        if ( hasResult )
            writer.Line( $"return {n.Result};" );

        writer.Close();
    }

    #endregion

    /// <summary>Every identifier the generated code declares, all sharing one collision-free prefix.</summary>
    private sealed class Names( string prefix )
    {
        public string Prefix { get; } = prefix;
        public string SharedLogger { get; } = prefix + "Logger";
        public string Logger { get; } = prefix + "_logger";
        public string Log { get; } = prefix + "_log";
        public string Task { get; } = prefix + "_task";
        public string Result { get; } = prefix + "_result";
        public string Exception { get; } = prefix + "_exception";
        public string Await { get; } = prefix + "_Await";
    }

    private sealed class Writer
    {
        private readonly StringBuilder _builder = new();
        private int _depth;

        public void Line( string text = "" )
        {
            if ( text.Length > 0 )
                _builder.Append( ' ', _depth * 4 ).Append( text );

            _builder.Append( '\n' );
        }

        public void Open( string? header = null )
        {
            if ( header is not null )
                Line( header );

            Line( "{" );
            _depth++;
        }

        public void Close()
        {
            _depth--;
            Line( "}" );
        }

        public override string ToString() => _builder.ToString();
    }
}
